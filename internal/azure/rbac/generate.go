// Definition is the custom role generated from what a principal called: exactly those actions and
// data actions, assignable at the narrowest scope that covers every call, and assigned there.
type Definition struct {
	Name, ID, Principal, Kind string
	Actions, DataActions      []string
	Scope                     string // where the role is assigned
	Assignable                string // assignableScopes: Scope, at most as deep as a resource group
}

var unsafe = regexp.MustCompile(`[^a-z0-9._-]+`)

// RoleName is the name of the role generated for a principal: pogi-<name>.
func RoleName(name string) string {
	return "pogi-" + strings.Trim(unsafe.ReplaceAllString(strings.ToLower(name), "-"), "-")
}

// guid is a UUID derived from a seed, so attaching twice updates the same role and assignment.
func guid(seed string) string {
	h := sha1.Sum([]byte("pogi:" + seed))
	h[6], h[8] = h[6]&0x0f|0x50, h[8]&0x3f|0x80
	x := hex.EncodeToString(h[:16])
	return x[:8] + "-" + x[8:12] + "-" + x[12:16] + "-" + x[16:20] + "-" + x[20:]
}

// Definition is the generated role for the principal.
func (p Principal) Definition() Definition {
	d := Definition{Name: RoleName(p.Name), ID: guid("role:" + p.OID), Principal: p.OID, Kind: p.Kind}
	var scopes []string
	for _, c := range p.Actions {
		if c.Data {
			d.DataActions = append(d.DataActions, c.Action)
		} else {
			d.Actions = append(d.Actions, c.Action)
		}
		scopes = append(scopes, c.Scope)
	}
	slices.Sort(d.Actions)
	slices.Sort(d.DataActions)
	d.Actions, d.DataActions = slices.Compact(d.Actions), slices.Compact(d.DataActions)
	d.Scope = commonScope(scopes)
	d.Assignable = d.Scope
	if seg := strings.Split(d.Scope, "/"); len(seg) > 5 { // /subscriptions/s/resourceGroups/g/...
		d.Assignable = strings.Join(seg[:5], "/")
	}
	return d
}

// commonScope is the deepest scope that contains every one of scopes.
func commonScope(scopes []string) string {
	if len(scopes) == 0 {
		return "/subscriptions/" + core.AzureSubscription
	}
	common := strings.Split(strings.Trim(scopes[0], "/"), "/")
	for _, s := range scopes[1:] {
		seg := strings.Split(strings.Trim(s, "/"), "/")
		n := 0
		for n < len(common) && n < len(seg) && strings.EqualFold(common[n], seg[n]) {
			n++
		}
		common = common[:n]
	}
	if len(common) < 2 { // different subscriptions: the first one
		return "/subscriptions/" + strings.Split(strings.Trim(scopes[0], "/"), "/")[1]
	}
	return "/" + strings.Join(common, "/")
}

func (d Definition) body(desc string) map[string]any {
	l := func(a []string) []string {
		if a == nil {
			return []string{}
		}
		return a
	}
	return map[string]any{"properties": map[string]any{"roleName": d.Name, "type": "CustomRole", "description": desc, "assignableScopes": []string{d.Assignable},
		"permissions": []any{map[string]any{"actions": l(d.Actions), "notActions": []string{}, "dataActions": l(d.DataActions), "notDataActions": []string{}}}}}
}

const description = "Generated by pogi from the calls recorded for this principal"

// JSON is the PUT body of the role definition, as ARM takes it.
func (d Definition) JSON() string {
	b, _ := json.MarshalIndent(d.body(description), "", "  ")
	return string(b)
}

// CLI is the Azure CLI that creates the role and assigns it.
func (d Definition) CLI() string {
	def, _ := json.Marshal(map[string]any{"Name": d.Name, "IsCustom": true, "Description": description, "Actions": nonNil(d.Actions),
		"DataActions": nonNil(d.DataActions), "AssignableScopes": []string{d.Assignable}})
	typ := map[string]string{"managedIdentity": "ServicePrincipal", "servicePrincipal": "ServicePrincipal", "user": "User"}[d.Kind]
	return fmt.Sprintf("az role definition create --role-definition '%s'\naz role assignment create --assignee-object-id %s --assignee-principal-type %s --role %s --scope %s\n",
		def, d.Principal, typ, d.Name, d.Scope)
}

func nonNil(a []string) []string {
	if a == nil {
		return []string{}
	}
	return a
}

// Closest is the built-in role that covers most of what the principal called, with how many of its
// distinct calls that is; a role that covers the same is preferred when it is narrower.
func (p Principal) Closest() (name string, covered int) {
	best, bestCost := 0, 0
	for _, r := range arm.Roles {
		n := 0
		for _, c := range p.Actions {
			allow, not := r.Actions, r.NotActions
			if c.Data {
				allow, not = r.Data, r.NotData
			}
			if matchAny(allow, c.Action) && !matchAny(not, c.Action) {
				n++
			}
		}
		cost := len(r.Actions) + len(r.Data)
		for _, a := range append(slices.Clone(r.Actions), r.Data...) {
			cost += 10 * strings.Count(a, "*")
		}
		if n > best || (n == best && n > 0 && cost < bestCost) {
			name, best, bestCost = r.Name, n, cost
		}
	}
	return name, best
}

// Plan is what attaching would do, for the diff the console shows before it does it.
type Plan struct {
	Def              Definition
	Doc              string   // the role definition that results
	Existing         bool     // the role exists: attaching updates it
	Add              []string // actions and data actions it gains
	AssignmentExists bool
}

// plan merges the recorded calls into the role that already exists for the principal, if any, so an
// attach never takes away what an earlier one granted.
func (s *Service) plan(p Principal) Plan {
	d := p.Definition()
	pl := Plan{Def: d}
	if old, ok := s.arm().Role(d.ID); ok && old.Name == d.Name {
		pl.Existing = true
		for _, a := range d.Actions {
			if !slices.ContainsFunc(old.Actions, func(o string) bool { return strings.EqualFold(o, a) }) {
				pl.Add = append(pl.Add, a)
			}
		}
		for _, a := range d.DataActions {
			if !slices.ContainsFunc(old.Data, func(o string) bool { return strings.EqualFold(o, a) }) {
				pl.Add = append(pl.Add, a)
			}
		}
		d.Actions, d.DataActions = union(old.Actions, d.Actions), union(old.Data, d.DataActions)
		pl.Def = d
	} else {
		pl.Add = append(slices.Clone(d.Actions), d.DataActions...)
	}
	pl.Doc = d.JSON()
	for _, a := range s.assignments() {
		pl.AssignmentExists = pl.AssignmentExists || (strings.EqualFold(a.principal, p.OID) && strings.EqualFold(a.role, d.ID) && strings.EqualFold(a.scope, d.Scope))
	}
	return pl
}

func union(a, b []string) []string {
	out := slices.Clone(a)
	for _, x := range b {
		if !slices.ContainsFunc(out, func(o string) bool { return strings.EqualFold(o, x) }) {
			out = append(out, x)
		}
	}
	slices.Sort(out)
	return out
}

func (s *Service) principal(oid string) (Principal, error) {
	for _, p := range Recorded(s.h) {
		if p.OID == oid {
			return p, nil
		}
	}
	return Principal{}, fmt.Errorf("%s has no recorded calls", oid)
}

// Preview is the plan of attaching the generated role to the principal.
func Preview(hub *core.Hub, oid string) (Plan, error) {
	s := service(hub)
	if s == nil || s.arm() == nil {
		return Plan{}, fmt.Errorf("Azure RBAC is not running")
	}
	p, err := s.principal(oid)
	if err != nil {
		return Plan{}, err
	}
	return s.plan(p), nil
}

// Attachment is what an attach created, so it can be undone.
type Attachment struct {
	Principal, Role, RoleID, Assignment, Scope string
	Existed                                    bool // the role existed: undo restores it, and does not delete it
}

func roleDefPath(scope, id string) string {
	sub := core.AzureSubscription
	if seg := strings.Split(strings.Trim(scope, "/"), "/"); len(seg) >= 2 {
		sub = seg[1]
	}
	return "/subscriptions/" + sub + "/providers/Microsoft.Authorization/roleDefinitions/" + id
}

// Attach creates (or updates) the principal's pogi-<name> role definition and assigns it at the
// narrowest scope covering its calls, through the Resource Manager's own storage.
func Attach(hub *core.Hub, oid string) (Attachment, error) {
	s := service(hub)
	if s == nil || s.arm() == nil {
		return Attachment{}, fmt.Errorf("Azure RBAC is not running")
	}
	p, err := s.principal(oid)
	if err != nil {
		return Attachment{}, err
	}
	pl := s.plan(p)
	d, c, a := pl.Def, &core.Ctx{Hub: hub, Internal: true, Cloud: core.Azure}, s.arm()
	defPath := roleDefPath(d.Scope, d.ID)
	if old := a.Generic("Microsoft.Authorization/roleDefinitions"); pl.Existing {
		for _, o := range old {
			if o["name"] == d.ID {
				s.mu.Lock()
				s.prev[d.ID] = o
				s.mu.Unlock()
			}
		}
	}
	if _, err := a.Put(c, defPath, d.body(description)); err != nil {
		return Attachment{}, err
	}
	asg := d.Scope + "/providers/Microsoft.Authorization/roleAssignments/" + guid("assignment:"+oid+":"+strings.ToLower(d.Scope))
	typ := map[string]string{"user": "User"}[p.Kind]
	if typ == "" {
		typ = "ServicePrincipal"
	}
	if _, err := a.Put(c, asg, map[string]any{"properties": map[string]any{"roleDefinitionId": defPath, "principalId": oid, "principalType": typ, "scope": d.Scope}}); err != nil {
		return Attachment{}, err
	}
	return Attachment{Principal: oid, Role: d.Name, RoleID: d.ID, Assignment: asg, Scope: d.Scope, Existed: pl.Existing}, nil
}

// Undo deletes the assignment an attach made and restores the role definition it replaced, or
// deletes it when the attach created it.
func Undo(hub *core.Hub, at Attachment) error {
	s := service(hub)
	if s == nil || s.arm() == nil {
		return fmt.Errorf("Azure RBAC is not running")
	}
	c, a := &core.Ctx{Hub: hub, Internal: true, Cloud: core.Azure}, s.arm()
	if !strings.Contains(strings.ToLower(at.Assignment), assignMarker) {
		return fmt.Errorf("not a role assignment: %s", at.Assignment)
	}
	if err := a.Delete(c, at.Assignment); err != nil {
		return err
	}
	s.mu.Lock()
	prev := s.prev[at.RoleID]
	delete(s.prev, at.RoleID)
	s.mu.Unlock()
	defPath := roleDefPath(at.Scope, at.RoleID)
	if prev != nil && at.Existed {
		_, err := a.Put(c, defPath, map[string]any{"properties": prev["properties"]})
		return err
	}
	return a.Delete(c, defPath)
}
