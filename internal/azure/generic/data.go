// The data services (Data Factory, Batch, Managed Grafana, Cognitive Services, Databricks, AI Search, Synapse,
// Data Explorer, Stream Analytics) store what is sent and fill what Terraform reads back: host names, endpoints,
// keys. Nothing runs behind them: no pipeline, pool, search index or query.

const (
	cognitive = "Microsoft.CognitiveServices/accounts"
	batchAcct = "Microsoft.Batch/batchAccounts"
	search    = "Microsoft.Search/searchServices"
)

// host is the lower-cased name of a resource, for the host names it gets.
func host(id arm.ID) string { return strings.ToLower(id.Name()) }

// loc is the location of a resource without spaces, as a host name has it ("westus2").
func loc(r map[string]any) string {
	return strings.ToLower(strings.ReplaceAll(armres.Str(r, "location"), " ", ""))
}

// setProps sets computed properties; Azure's service owns them, so they win over what a client sent.
func setProps(r map[string]any, kv map[string]any) {
	p := armres.Props(r)
	for k, v := range kv {
		p[k] = v
	}
	r["properties"] = p
}

func init() {
	// Cognitive Services: by the owner's decision pogi does not emulate Azure OpenAI.
	Override(cognitive, Hook{
		Put: func(s *Service, c *core.Ctx, id arm.ID, r map[string]any) error {
			if k := armres.Str(r, "kind"); strings.EqualFold(k, "OpenAI") || strings.EqualFold(k, "AIServices") {
				return core.Errorf(http.StatusBadRequest, "InvalidRequestContent",
					"pogi does not emulate Azure OpenAI: an account of kind '%s' is not supported.", k)
			}
			return nil
		},
		View: func(s *Service, id arm.ID, r map[string]any) {
			p := armres.Props(r)
			ep := "https://" + loc(r) + ".api.cognitive.microsoft.com/"
			if sub := armres.Str(p, "customSubDomainName"); sub != "" {
				ep = "https://" + strings.ToLower(sub) + ".cognitiveservices.azure.com/"
			}
			setProps(r, map[string]any{"endpoint": ep, "internalId": fmt.Sprintf("%x", key(id))[:32]})
		},
		Actions: map[string]func(*Service, *core.Ctx, arm.ID, map[string]any) (any, error){
			"listKeys": func(s *Service, c *core.Ctx, id arm.ID, _ map[string]any) (any, error) {
				return map[string]any{"key1": armres.Key("cognitive/key1/" + key(id)), "key2": armres.Key("cognitive/key2/" + key(id))}, nil
			},
		},
	})

	Override(batchAcct, Hook{
		View: func(s *Service, id arm.ID, r map[string]any) {
			setProps(r, map[string]any{
				"accountEndpoint":                       host(id) + "." + loc(r) + ".batch.azure.com",
				"nodeManagementEndpoint":                fmt.Sprintf("%s.%s.service.batch.azure.com", host(id), loc(r)),
				"dedicatedCoreQuota":                    20,
				"lowPriorityCoreQuota":                  100,
				"poolQuota":                             100,
				"activeJobAndJobScheduleQuota":          300,
				"dedicatedCoreQuotaPerVMFamilyEnforced": false,
			})
		},
		Actions: map[string]func(*Service, *core.Ctx, arm.ID, map[string]any) (any, error){
			"listKeys": func(s *Service, c *core.Ctx, id arm.ID, _ map[string]any) (any, error) {
				return map[string]any{"accountName": id.Name(), "primary": armres.Key("batch/primary/" + key(id)), "secondary": armres.Key("batch/secondary/" + key(id))}, nil
			},
		},
	})
	Override(batchAcct+"/pools", Hook{View: func(s *Service, id arm.ID, r map[string]any) {
		setProps(r, map[string]any{"allocationState": "Steady", "currentDedicatedNodes": 0, "currentLowPriorityNodes": 0})
	}})

	Override("Microsoft.Dashboard/grafana", Hook{
		Put: func(s *Service, c *core.Ctx, id arm.ID, r map[string]any) error {
			armres.Defaults(armres.Props(r), map[string]any{"publicNetworkAccess": "Enabled", "zoneRedundancy": "Disabled",
				"apiKey": "Disabled", "deterministicOutboundIP": "Disabled", "autoGeneratedDomainNameLabelScope": "TenantReuse"})
			return nil
		},
		View: func(s *Service, id arm.ID, r map[string]any) {
			setProps(r, map[string]any{"endpoint": fmt.Sprintf("https://%s-%s.%s.grafana.azure.com", host(id), id.Name()[:min(len(id.Name()), 8)], loc(r)),
				"grafanaVersion": "12.0.0"})
		},
	})

	Override("Microsoft.Databricks/workspaces", Hook{
		Put: func(s *Service, c *core.Ctx, id arm.ID, r map[string]any) error {
			armres.Defaults(armres.Props(r), map[string]any{"publicNetworkAccess": "Enabled", "requiredNsgRules": "AllRules"})
			return nil
		},
		View: func(s *Service, id arm.ID, r map[string]any) {
			n := workspaceNumber(id)
			setProps(r, map[string]any{"workspaceId": fmt.Sprintf("%d", n), "workspaceUrl": fmt.Sprintf("adb-%d.%d.azuredatabricks.net", n, n%20)})
		},
	})

	Override(search, Hook{
		Put: func(s *Service, c *core.Ctx, id arm.ID, r map[string]any) error {
			armres.Defaults(armres.Props(r), map[string]any{"replicaCount": 1, "partitionCount": 1, "hostingMode": "default",
				"publicNetworkAccess": "enabled", "status": "running", "statusDetails": ""})
			return nil
		},
		Actions: map[string]func(*Service, *core.Ctx, arm.ID, map[string]any) (any, error){
			"listAdminKeys": func(s *Service, c *core.Ctx, id arm.ID, _ map[string]any) (any, error) {
				return map[string]any{"primaryKey": armres.Key("search/primary/" + key(id)), "secondaryKey": armres.Key("search/secondary/" + key(id))}, nil
			},
			"listQueryKeys": func(s *Service, c *core.Ctx, id arm.ID, _ map[string]any) (any, error) {
				return map[string]any{"value": []any{map[string]any{"name": "default", "key": armres.Key("search/query/" + key(id))}}}, nil
			},
		},
	})
}

// workspaceNumber is the stable number of a Databricks workspace in its URL.
func workspaceNumber(id arm.ID) int {
	n := 0
	for _, b := range []byte(key(id)) {
		n = (n*31 + int(b)) % 9000000000
	}
	return 1000000000000000 + n
}

// Synapse: a new SQL pool starts with its transparent data encryption and geo backup policy, which azurerm
// reads right after it creates the pool.
func init() {
	const pool = "Microsoft.Synapse/workspaces/sqlPools"
	Override(pool, Hook{
		Put: func(s *Service, c *core.Ctx, id arm.ID, r map[string]any) error {
			armres.Defaults(armres.Props(r), map[string]any{"status": "Online", "collation": "SQL_Latin1_General_CP1_CI_AS"})
			if s.Has(id) {
				return nil
			}
			if err := s.Create(c, id.Child("transparentDataEncryption", "current"), map[string]any{"properties": map[string]any{"status": "Disabled"}}); err != nil {
				return err
			}
			return s.Create(c, id.Child("geoBackupPolicies", "Default"), map[string]any{"properties": map[string]any{"state": "Enabled"}})
		},
	})
}

// Data Factory: a factory has a provisioning state, but its pipelines, datasets and linked services do not
// (azurerm keeps unknown properties of a dataset and shows them as drift).
func init() {
	for _, t := range []string{"pipelines", "datasets", "linkedservices"} {
		Override("Microsoft.DataFactory/factories/"+t, Hook{Put: func(s *Service, c *core.Ctx, id arm.ID, r map[string]any) error {
			delete(armres.Props(r), "provisioningState")
			return nil
		}})
	}
}

// Data Explorer: a cluster is running at once, with the addresses of its query and ingestion endpoints.
func init() {
	Override("Microsoft.Kusto/clusters", Hook{View: func(s *Service, id arm.ID, r map[string]any) {
		setProps(r, map[string]any{"state": "Running",
			"uri":              fmt.Sprintf("https://%s.%s.kusto.windows.net", host(id), loc(r)),
			"dataIngestionUri": fmt.Sprintf("https://ingest-%s.%s.kusto.windows.net", host(id), loc(r))})
	}})
}
