var update = flag.Bool("update", false, "rewrite docs/reference/aws-long-tail.md")

// TestCoverage walks every embedded model. For each service it takes the main
// resource the engine inferred (a type with create and delete operations and a
// get or list one), builds a minimal valid input from the model's required
// members, and drives create, get, list and delete as raw protocol requests
// through a hub. The result is a table, written to docs/reference/aws-long-tail.md with
// `go test ./internal/aws/generic -run Coverage -update`.
func TestCoverage(t *testing.T) {
	names := core.SortedKeys(loadIndex())
	rows := make([]covRow, len(names))
	t.Run("services", func(t *testing.T) {
		for i, n := range names {
			t.Run(n, func(t *testing.T) {
				t.Parallel()
				rows[i] = coverService(t, n)
				if rows[i].result == "fail" {
					t.Errorf("%s: %s", rows[i].typ, rows[i].reason)
				}
			})
		}
	})
	doc := coverDoc(rows)
	t.Log("\n" + doc)
	if *update {
		if err := os.WriteFile("../../../docs/reference/aws-long-tail.md", []byte(doc), 0o644); err != nil {
			t.Error(err)
		}
	}
}

type covRow struct {
	svc, protocol, typ, result, reason string
}

func coverDoc(rows []covRow) string {
	n := map[string]int{}
	for _, r := range rows {
		n[r.result]++
	}
	var b strings.Builder
	fmt.Fprintf(&b, "---\ntitle: AWS long-tail services\ndescription: The AWS services built from API models, and what a create, get, list and delete run finds.\n---\n\n"+
		"# AWS long-tail services\n\n"+
		"<!-- Generated by `go test ./internal/aws/generic -run Coverage -update`; do not edit. -->\n\n"+
		"pogi builds these AWS services from the API model AWS publishes for each one, as shipped in botocore (the Python SDK). The code is in `internal/aws/generic`.\n"+
		"For each service, the test picks its main resource, guessing from the operation names. It builds the smallest valid input from the\n"+
		"model's required fields, then sends create, get, list and delete as raw HTTP requests in the service's own wire format. It checks that no response is a\n"+
		"server error, that the new resource appears in the list, and that a get after the delete says not found. Hand-written overrides\n"+
		"are part of the run, so the table shows what a client gets today, not what the model alone gives. Some of these services\n"+
		"also have their own row on [Coverage](coverage.md), so this table is longer than the long-tail row on that page.\n\n"+
		"%d services: %d pass, %d overridden (validated by their own tests), %d fail, %d where the test found no resource to drive (\"no inferable resource\").\n\n", len(rows), n["pass"], n["overridden"], n["fail"], n["no inferable resource"])
	b.WriteString("| Service | Protocol | Resource | Result | Reason |\n|---|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", r.svc, r.protocol, r.typ, r.result, strings.ReplaceAll(r.reason, "|", "/"))
	}
	return b.String()
}

// mainType picks the type to drive: one with create, delete, get and list
// operations if there is one, then the one whose create call needs the fewest
// members, then the first by name.
func mainType(m *model) *rtype {
	var best *rtype
	score := func(t *rtype) [2]int {
		s := [2]int{0, len(createOp(t).in.Required)}
		if len(t.ops[kRead]) == 0 || len(t.ops[kList]) == 0 {
			s[0] = 1
		}
		return s
	}
	for _, n := range core.SortedKeys(m.types) {
		t := m.types[n]
		if len(t.ops[kCreate]) == 0 || len(t.ops[kDelete]) == 0 || len(t.ops[kRead])+len(t.ops[kList]) == 0 || createOp(t).in == nil {
			continue
		}
		if sc := score(t); best == nil || sc[0] < score(best)[0] || sc[0] == score(best)[0] && sc[1] < score(best)[1] {
			best = t
		}
	}
	return best
}

// opOf picks an operation of a kind: the one named <Verb><Type> if any, else the first.
func opOf(t *rtype, k kind, verbs ...string) *operation {
	ops := t.ops[k]
	for _, v := range verbs {
		for _, o := range ops {
			if o.Name == v+t.name {
				return o
			}
		}
	}
	if len(ops) == 0 {
		return nil
	}
	return ops[0]
}

func createOp(t *rtype) *operation { return opOf(t, kCreate, "Create", "Put", "Register") }

type driver struct {
	m    *model
	url  string
	svc  *Service
	typ  *rtype
	know map[string]any // identifiers of the created resource, by member name
	res  *Resource      // the created resource
}

// elsewhere are services whose resources live in other services, so a
// one-service walk can't create them; their own tests cover them.
var elsewhere = map[string]string{
	"cloudcontrol": "provisions through other services (cloudcontrol_test.go)",
	// safety rules hang off a control panel, so a one-type walk can't list them
	"route53-recovery-control-config": "main resources are clusters and control panels (route53recoverycontrolconfig_test.go)",
	"appstream":                       "the walk picks the account's usage report subscription, which has no identifier to look for (appstream_test.go drives stacks)",
}

// keptAfterDelete are services whose deleted resource stays readable in a DELETED state, as in AWS
// (their own tests check it).
var keptAfterDelete = map[string]bool{"medialive": true}

func coverService(t *testing.T, name string) covRow {
	h, base := core.ServeTest(t, func(h *core.Hub) core.Service { return New(h, name) })
	svc := h.Service(name).(*Service)
	m, err := svc.model()
	if err != nil {
		t.Fatal(err)
	}
	row := covRow{svc: name, protocol: m.meta.Protocol}
	if why, ok := elsewhere[name]; ok {
		row.result, row.reason = "no inferable resource", why
		return row
	}
	typ := mainType(m)
	if typ == nil {
		row.result, row.reason = "no inferable resource", "no type with create, delete and get or list operations"
		return row
	}
	row.typ = typ.name
	d := &driver{m: m, url: base, svc: svc, typ: typ}
	switch row.reason = d.run(); {
	case row.reason == "":
		row.result = "pass"
	case overridden(name, createOp(typ).Name) && strings.Contains(row.reason, ": 4"):
		// a hand-written create validates its input, which the walk's minimal values don't satisfy;
		// the service's own tests drive it with real values
		row.result = "overridden"
	default:
		row.result = "fail"
	}
	return row
}

// overridden says whether a service's operation has a hand-written override.
func overridden(service, op string) bool {
	reg.Lock()
	defer reg.Unlock()
	return reg.over[service+"/"+op] != nil
}

// run drives the four calls and returns what went wrong, or "".
func (d *driver) run() string {
	t := d.typ
	create := createOp(t)
	if _, why := d.call(create); why != "" {
		return why
	}
	var res *Resource
	d.svc.mu.Lock()
	for _, r := range d.svc.st.Res {
		if r.Type == t.name {
			res = r.clone()
		}
	}
	d.svc.mu.Unlock()
	if res == nil {
		return create.Name + ": nothing was stored"
	}
	d.res, d.know = res, map[string]any{}
	for k, v := range res.IDs {
		d.know[k] = v
	}
	read, list, del := opOf(t, kRead, "Get", "Describe"), opOf(t, kList, "List", "Describe"), opOf(t, kDelete, "Delete", "Deregister")
	var ids []string
	for _, v := range append([]string{res.Name, res.ID, res.ARN}, mapValues(res.IDs)...) {
		if v != "" {
			ids = append(ids, v)
		}
	}
	listed := func(want bool) string {
		status, body, err := d.send(list, d.input(list))
		switch {
		case err != nil:
			return err.Error()
		case !want && notFound(status, body): // a list narrowed by an identifier that matches nothing is not-found
			return ""
		case status/100 != 2:
			return fmt.Sprintf("%s: %d %s", list.Name, status, snippet(body))
		}
		for _, id := range ids {
			if strings.Contains(body, id) == want {
				return ""
			}
		}
		return fmt.Sprintf("%s: the resource is %slisted", list.Name, map[bool]string{true: "not ", false: "still "}[want])
	}
	if read != nil {
		if _, why := d.call(read); why != "" {
			return why
		}
	}
	if list != nil {
		if why := listed(true); why != "" {
			return why
		}
	}
	if _, why := d.call(del); why != "" {
		return why
	}
	if read == nil {
		return listed(false)
	}
	status, body, err := d.send(read, d.input(read))
	switch {
	case err != nil:
		return err.Error()
	case status >= 500:
		return fmt.Sprintf("%s after delete: %d %s", read.Name, status, snippet(body))
	case !notFound(status, body) && !keptAfterDelete[d.svc.meta.Name]:
		return fmt.Sprintf("%s after delete: %d %s, want not found", read.Name, status, snippet(body))
	}
	return ""
}

var notFoundRE = regexp.MustCompile(`(?i)not.?found|no.?such|not.?exist|does.?not|could.?not.?find|unknown|nonexist`)

func notFound(status int, body string) bool {
	return status == 404 || status >= 400 && status < 500 && notFoundRE.MatchString(body)
}

func snippet(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > 160 {
		s = s[:160] + "..."
	}
	return s
}

// call sends an operation with an input built from the model and what is known, and wants a 2xx.
func (d *driver) call(op *operation) (body, why string) {
	status, body, err := d.send(op, d.input(op))
	switch {
	case err != nil:
		return "", op.Name + ": " + err.Error()
	case status/100 != 2:
		return body, fmt.Sprintf("%s: %d %s", op.Name, status, snippet(body))
	}
	return body, ""
}

// input builds the members of an operation a client would send: the required ones, the type's identifiers,
// and (but for list calls) any optional name, id or ARN. Known values come first, else the smallest valid ones.
func (d *driver) input(op *operation) map[string]any {
	in := map[string]any{}
	sh := op.in
	if sh == nil {
		return in
	}
	idx := normIndex(d.know)
	want := slices.Clone(sh.Required)
	for _, n := range sh.names {
		mr := sh.Members[n]
		if slices.Contains(want, n) || mr.Location != "" && mr.Location != "uri" {
			continue
		}
		if slices.Contains(d.typ.ids, n) || op.kind != kList && mr.sh.Type == "string" && identLike(n) != "" {
			want = append(want, n)
		}
	}
	for _, n := range want {
		mr := sh.Members[n]
		if mr == nil {
			continue
		}
		if v, ok := d.know[n]; ok {
			in[n] = v
		} else if v, ok := lookupIn(idx, n, d.typ); ok {
			in[n] = v
		} else if k := identLike(n); k == "arn" && d.res != nil && d.res.ARN != "" && mr.sh.Type == "string" {
			in[n] = d.res.ARN
		} else if k != "" && d.res != nil && d.res.Key != "" && mr.sh.Type == "string" {
			in[n] = strings.Split(d.res.Key, "/")[0]
		} else {
			in[n] = minimal(mr, n, 0)
		}
	}
	return in
}

// identLike says whether a member is named like an identifier: "arn" for Arn, "id" for Id, Name and Identifier.
func identLike(n string) string {
	switch {
	case strings.HasSuffix(n, "Arn") || strings.HasSuffix(n, "ARN"):
		return "arn"
	case strings.HasSuffix(n, "Id") || strings.HasSuffix(n, "ID") || strings.HasSuffix(n, "Name") || strings.HasSuffix(n, "Identifier"):
		return "id"
	}
	return ""
}

// minimal is the smallest valid value of a member.
func minimal(r *ref, name string, depth int) any {
	sh := r.sh
	switch sh.Type {
	case "structure":
		out := map[string]any{}
		if depth < 8 {
			for _, n := range sh.Required {
				if mr := sh.Members[n]; mr != nil {
					out[n] = minimal(mr, n, depth+1)
				}
			}
			if len(out) == 0 && len(sh.names) > 0 { // an empty structure does not survive the Query protocol, and a union needs a member
				out[sh.names[0]] = minimal(sh.Members[sh.names[0]], sh.names[0], depth+1)
			}
		}
		return out
	case "list":
		n := 1
		if sh.Min != nil && int(*sh.Min) > 1 {
			n = min(int(*sh.Min), 5)
		}
		out := []any{}
		for range n {
			if depth < 8 {
				out = append(out, minimal(sh.Member, name, depth+1))
			}
		}
		return out
	case "map":
		if depth >= 8 {
			return map[string]any{}
		}
		return map[string]any{str(minimal(sh.Key, "key", depth+1)): minimal(sh.Value, name, depth+1)}
	case "integer", "long", "float", "double":
		v := 1.0
		if sh.Min != nil {
			v = max(v, *sh.Min)
		}
		if sh.Max != nil {
			v = min(v, *sh.Max)
		}
		return v
	case "boolean":
		return false
	case "timestamp":
		return "2024-01-01T00:00:00Z"
	case "blob":
		return base64.StdEncoding.EncodeToString([]byte("pogi"))
	case "string":
		lo, hi := 1, 1<<20
		if sh.Min != nil {
			lo = int(*sh.Min)
		}
		if sh.Max != nil {
			hi = int(*sh.Max)
		}
		switch {
		case len(sh.Enum) > 0:
			return sh.Enum[0]
		case sh.Pattern != "":
			if s, ok := fromPattern(sh.Pattern, lo, hi); ok {
				return s
			}
		}
		s := "pogi"
		if role(name) == "arn" {
			s = "arn:aws:pogi:us-east-1:000000000000:pogi/pogi"
		}
		for len(s) < lo {
			s += "a"
		}
		return s[:min(len(s), hi)]
	}
	return map[string]any{}
}

// ---- encoding requests

func (d *driver) send(op *operation, in map[string]any) (int, string, error) {
	req, err := d.request(op, in)
	if err != nil {
		return 0, "", err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return 0, "", err
	}
	defer resp.Body.Close()
	b, _ := io.ReadAll(resp.Body)
	return resp.StatusCode, string(b), nil
}

func (d *driver) request(op *operation, in map[string]any) (*http.Request, error) {
	md := d.m.meta
	hdr := http.Header{}
	method, path, query := http.MethodPost, "/", url.Values{}
	var body []byte
	switch md.Protocol {
	case "json":
		hdr.Set("Content-Type", "application/x-amz-json-"+d.m.jsonVersion())
		hdr.Set("X-Amz-Target", md.TargetPrefix+"."+op.Name)
		body, _ = json.Marshal(toJSON(op.Input, op.in, in, true, false))
	case "query", "ec2":
		form := url.Values{"Action": {op.Name}, "Version": {md.APIVersion}}
		if op.in != nil {
			encQ(form, "", nil, op.in, in, md.Protocol == "ec2")
		}
		hdr.Set("Content-Type", "application/x-www-form-urlencoded")
		body = []byte(form.Encode())
	default:
		method = op.HTTP.Method
		var q string
		path, q, _ = strings.Cut(op.HTTP.RequestURI, "?")
		for p := range strings.SplitSeq(q, "&") {
			if p != "" {
				k, v, _ := strings.Cut(p, "=")
				query.Add(k, v)
			}
		}
		if sh := op.in; sh != nil {
			hasBody := false
			for _, n := range sh.names {
				mr := sh.Members[n]
				v, ok := in[n]
				ln := locName(n, mr)
				switch mr.Location {
				case "uri":
					segs := strings.Split(str(v), "/")
					for i := range segs {
						segs[i] = url.PathEscape(segs[i])
					}
					path = strings.Replace(path, "{"+ln+"+}", strings.Join(segs, "/"), 1)
					path = strings.Replace(path, "{"+ln+"}", url.PathEscape(str(v)), 1)
				case "querystring":
					if mm, isMap := v.(map[string]any); isMap {
						for k, y := range mm {
							query.Add(k, str(y))
						}
					} else if l, isList := v.([]any); isList {
						for _, x := range l {
							query.Add(ln, str(x))
						}
					} else if ok {
						query.Add(ln, str(v))
					}
				case "header":
					if ok {
						hdr.Set(ln, str(v))
					}
				case "headers":
					mm, _ := v.(map[string]any)
					for k, y := range mm {
						hdr.Set(ln+k, str(y))
					}
				default:
					hasBody = hasBody || ok
				}
			}
			body = d.restBody(op, in, hasBody)
			if len(body) > 0 && sh.Payload == "" {
				hdr.Set("Content-Type", map[bool]string{true: "application/xml", false: "application/json"}[md.Protocol == "rest-xml"])
			}
		}
	}
	u := d.url + path
	if len(query) > 0 {
		u += "?" + query.Encode()
	}
	req, err := http.NewRequest(method, u, strings.NewReader(string(body)))
	if err != nil {
		return nil, err
	}
	req.Header = hdr
	signing := md.SigningName
	if signing == "" {
		signing = md.EndpointPrefix
	}
	req.Header.Set("Authorization", "AWS4-HMAC-SHA256 Credential=test/20260101/us-east-1/"+signing+"/aws4_request, SignedHeaders=host, Signature=0")
	return req, nil
}

func (d *driver) restBody(op *operation, in map[string]any, hasBody bool) []byte {
	sh := op.in
	isXML := d.m.meta.Protocol == "rest-xml"
	if sh.Payload != "" {
		pm, v := sh.Members[sh.Payload], in[sh.Payload]
		if v == nil {
			return nil
		}
		switch pm.sh.Type {
		case "blob":
			b, _ := base64.StdEncoding.DecodeString(str(v))
			return b
		case "string":
			return []byte(str(v))
		}
		if isXML {
			var b strings.Builder
			writeXML(&b, locName(sh.Payload, pm), pm, pm.sh, v, false)
			return []byte(b.String())
		}
		b, _ := json.Marshal(toJSON(pm, pm.sh, v, true, false))
		return b
	}
	if !hasBody {
		return nil
	}
	if isXML {
		var b strings.Builder
		writeXML(&b, locName(sh.Name, op.Input), op.Input, sh, in, false)
		return []byte(b.String())
	}
	b, _ := json.Marshal(toJSON(op.Input, sh, in, true, true))
	return b
}

// encQ writes a value as Query parameters, the inverse of qn.decode.
func encQ(f url.Values, prefix string, r *ref, sh *shape, v any, ec2 bool) {
	join := func(a, b string) string {
		if a == "" {
			return b
		}
		return a + "." + b
	}
	flat := ec2 || r != nil && r.Flattened || sh.Flattened
	switch sh.Type {
	case "structure":
		mm, _ := v.(map[string]any)
		for n, x := range mm {
			if mr := sh.Members[n]; mr != nil && x != nil {
				encQ(f, join(prefix, queryKey(n, mr, ec2)), mr, mr.sh, x, ec2)
			}
		}
	case "list":
		l, _ := v.([]any)
		base := prefix
		if !flat {
			base = join(prefix, locName("member", sh.Member))
		}
		for i, x := range l {
			encQ(f, base+"."+strconv.Itoa(i+1), sh.Member, sh.Member.sh, x, ec2)
		}
	case "map":
		mm, _ := v.(map[string]any)
		base := prefix
		if !flat {
			base += ".entry"
		}
		for i, k := range core.SortedKeys(mm) {
			e := base + "." + strconv.Itoa(i+1)
			f.Set(e+"."+locName("key", sh.Key), k)
			encQ(f, e+"."+locName("value", sh.Value), sh.Value, sh.Value.sh, mm[k], ec2)
		}
	case "timestamp":
		f.Set(prefix, str(fmtTime(v, tsFormat(r, sh, "iso8601"))))
	default:
		f.Set(prefix, str(v))
	}
}

func mapValues(m map[string]string) (out []string) {
	for _, k := range core.SortedKeys(m) {
		out = append(out, m[k])
	}
	return out
}
