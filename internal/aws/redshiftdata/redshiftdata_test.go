func must[T any](v T, err error) T {
	if err != nil {
		panic(err)
	}
	return v
}

func fails(t *testing.T, err error, code string) {
	t.Helper()
	var ae smithy.APIError
	if !errors.As(err, &ae) || ae.ErrorCode() != code {
		t.Fatalf("want %s, got %v", code, err)
	}
}

// serve runs the three Redshift services and Secrets Manager on one hub.
func serve(t *testing.T) (*redshift.Client, *redshiftdata.Client, *redshiftserverless.Client, *secretsmanager.Client) {
	_, url := core.ServeTest(t, func(h *core.Hub) core.Service { return redshiftsvc.New(h) },
		func(h *core.Hub) core.Service { return data.New(h) },
		func(h *core.Hub) core.Service { return serverless.New(h) },
		func(h *core.Hub) core.Service { return smsvc.New(h) })
	cfg := awstest.Config(t, url)
	return redshift.NewFromConfig(cfg), redshiftdata.NewFromConfig(cfg), redshiftserverless.NewFromConfig(cfg), secretsmanager.NewFromConfig(cfg)
}

func TestBind(t *testing.T) {
	q, args, err := data.Bind([]string{
		`CREATE TABLE t (id INT IDENTITY(100, 5) ENCODE az64, name VARCHAR(MAX) ENCODE zstd DISTKEY, ts TIMESTAMP SORTKEY,
			note VARCHAR(20) DEFAULT 'distkey') DISTSTYLE KEY COMPOUND SORTKEY (ts, id) BACKUP NO`,
		`INSERT INTO t (name, note) VALUES (:name, ':not_a_param'), (:name, 'x'::text)`,
		`SELECT * FROM t WHERE id > :min AND "odd:col" = 1 -- diststyle even stays: not DDL`,
	}, map[string]string{"name": "o'brien", "min": "0"})
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		`CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5) , name VARCHAR(65535) , ts TIMESTAMP , note VARCHAR(20) DEFAULT 'distkey')`,
		`INSERT INTO t (name, note) VALUES ($1, ':not_a_param'), ($1, 'x'::text)`,
		`SELECT * FROM t WHERE id > $1 AND "odd:col" = 1 -- diststyle even stays: not DDL`,
	}
	for i := range q {
		if got := strings.Join(strings.Fields(q[i]), " "); got != want[i] {
			t.Errorf("rewrote\n%s\nwant\n%s", got, want[i])
		}
	}
	if fmt.Sprint(args) != "[[] [o'brien] [0]]" {
		t.Fatalf("args %q", args)
	}
	for _, p := range []map[string]string{{}, {"min": "1", "unused": "2"}} {
		if _, _, err := data.Bind([]string{"SELECT :min"}, p); core.AsError(err).Code != "ValidationException" {
			t.Fatalf("parameters %v: %v", p, err)
		}
	}
}

func TestErrorsWithoutDocker(t *testing.T) {
	t.Setenv("DOCKER_HOST", "unix:///nonexistent")
	rs, ds, _, _ := serve(t)
	ctx := context.Background()
	must(rs.CreateCluster(ctx, &redshift.CreateClusterInput{ClusterIdentifier: aws.String("meta"), NodeType: aws.String("dc2.large"),
		MasterUsername: aws.String("awsuser"), MasterUserPassword: aws.String("Secret123")}))
	exec := func(in *redshiftdata.ExecuteStatementInput) error {
		in.Database = aws.String("dev")
		if in.Sql == nil {
			in.Sql = aws.String("SELECT 1")
		}
		_, err := ds.ExecuteStatement(ctx, in)
		return err
	}
	fails(t, exec(&redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String("nope")}), "ValidationException")
	fails(t, exec(&redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String("meta"), WorkgroupName: aws.String("wg")}), "ValidationException")
	fails(t, exec(&redshiftdata.ExecuteStatementInput{WorkgroupName: aws.String("wg")}), "ValidationException")
	fails(t, exec(&redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String("meta"), Sql: aws.String("SELECT :x")}), "ValidationException")
	fails(t, exec(&redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String("meta"), SecretArn: aws.String("nope")}), "ValidationException")
	fails(t, exec(&redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String("meta")}), "ExecuteStatementException")
	_, err := ds.BatchExecuteStatement(ctx, &redshiftdata.BatchExecuteStatementInput{ClusterIdentifier: aws.String("meta"), Database: aws.String("dev"),
		Sqls: []string{"SELECT 1"}})
	fails(t, err, "BatchExecuteStatementException")
	_, err = ds.DescribeStatement(ctx, &redshiftdata.DescribeStatementInput{Id: aws.String(core.UUID())})
	fails(t, err, "ResourceNotFoundException")
	_, err = ds.GetStatementResult(ctx, &redshiftdata.GetStatementResultInput{Id: aws.String("not-an-id")})
	fails(t, err, "ValidationException")
	_, err = ds.ListTables(ctx, &redshiftdata.ListTablesInput{ClusterIdentifier: aws.String("meta"), Database: aws.String("dev")})
	fails(t, err, "DatabaseConnectionException")
	if l := must(ds.ListStatements(ctx, &redshiftdata.ListStatementsInput{})); len(l.Statements) != 0 {
		t.Fatalf("statements %+v", l.Statements)
	}
}

// finished waits for a statement to end and checks that it finished.
func finished(t *testing.T, ds *redshiftdata.Client, id string) *redshiftdata.DescribeStatementOutput {
	t.Helper()
	for end := time.Now().Add(time.Minute); time.Now().Before(end); time.Sleep(50 * time.Millisecond) {
		d := must(ds.DescribeStatement(context.Background(), &redshiftdata.DescribeStatementInput{Id: aws.String(id)}))
		switch d.Status {
		case types.StatusStringFinished:
			return d
		case types.StatusStringFailed, types.StatusStringAborted:
			t.Fatalf("statement %s %s: %s", id, d.Status, aws.ToString(d.Error))
		}
	}
	t.Fatalf("statement %s did not finish", id)
	return nil
}

func eventually(t *testing.T, what string, cond func() bool) {
	t.Helper()
	for end := time.Now().Add(5 * time.Minute); !cond(); time.Sleep(200 * time.Millisecond) {
		if time.Now().After(end) {
			t.Fatalf("timed out waiting for %s", what)
		}
	}
}

// login connects to 127.0.0.1:port as user.
func login(t *testing.T, port int32, user, password, db string) *pgx.Conn {
	t.Helper()
	cfg := must(pgx.ParseConfig("sslmode=disable"))
	cfg.Host, cfg.Port, cfg.User, cfg.Password, cfg.Database = "127.0.0.1", uint16(port), user, password, db
	conn, err := pgx.ConnectConfig(context.Background(), cfg)
	if err != nil {
		t.Fatalf("login as %s: %v", user, err)
	}
	t.Cleanup(func() { conn.Close(context.Background()) })
	return conn
}

// TestEndToEnd runs a cluster and a serverless workgroup in real containers
// and drives them through the Data API, when a container engine answers.
func TestEndToEnd(t *testing.T) {
	d := docker.New(docker.Options{})
	if testing.Short() || !d.Available() {
		t.Skip("needs a running container engine")
	}
	rs, ds, sl, sm := serve(t)
	ctx, id := context.Background(), fmt.Sprintf("e2e-%d", os.Getpid())

	// 1. a cluster becomes available
	must(rs.CreateCluster(ctx, &redshift.CreateClusterInput{ClusterIdentifier: aws.String(id), NodeType: aws.String("ra3.xlplus"),
		MasterUsername: aws.String("awsuser"), MasterUserPassword: aws.String("Secret123"), DBName: aws.String("analytics")}))
	var port int32
	eventually(t, "the cluster (the first run pulls postgres)", func() bool {
		cl := must(rs.DescribeClusters(ctx, &redshift.DescribeClustersInput{ClusterIdentifier: aws.String(id)})).Clusters[0]
		if *cl.ClusterStatus == "hardware-failure" {
			t.Fatalf("the container failed: %+v", cl)
		}
		if *cl.ClusterStatus == "available" {
			port = *cl.Endpoint.Port
		}
		return port != 0
	})
	info := must(d.Inspect(ctx, "pogi-redshift-"+id))
	if info.HostPort(5439) != int(port) || info.Config.Labels[docker.LabelService] != "redshift" {
		t.Fatalf("container %+v, endpoint port %d", info, port)
	}

	// 2. the Data API: Redshift DDL, parameters, typed records, batches
	run := func(sql string, params ...string) *redshiftdata.DescribeStatementOutput {
		t.Helper()
		in := &redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"), Sql: aws.String(sql)}
		for i := 0; i+1 < len(params); i += 2 {
			in.Parameters = append(in.Parameters, types.SqlParameter{Name: aws.String(params[i]), Value: aws.String(params[i+1])})
		}
		return finished(t, ds, *must(ds.ExecuteStatement(ctx, in)).Id)
	}
	if st := run(`CREATE TABLE sales (id INT IDENTITY(1,1) ENCODE az64, region VARCHAR(MAX) ENCODE zstd DISTKEY, amount DECIMAL(10,2),
		qty BIGINT, price FLOAT8, paid BOOLEAN, sold TIMESTAMP SORTKEY, note VARCHAR(20)) DISTSTYLE KEY COMPOUND SORTKEY (sold, id)`); *st.HasResultSet {
		t.Fatalf("create %+v", st)
	}
	if st := run(`INSERT INTO sales (region, amount, qty, price, paid, sold) VALUES (:region, :amount, :qty, :price, :paid, :sold)`,
		"region", "emea", "amount", "12.50", "qty", "3", "price", "4.25", "paid", "true", "sold", "2024-05-01 10:00:00"); st.ResultRows != 1 {
		t.Fatalf("insert %+v", st)
	}
	batch := must(ds.BatchExecuteStatement(ctx, &redshiftdata.BatchExecuteStatementInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"),
		Sqls:       []string{"INSERT INTO sales (region, qty) VALUES (:r, 1)", "INSERT INTO sales (region, qty) VALUES ('apac', 2)", "SELECT count(*) AS n FROM sales"},
		Parameters: []types.SqlParameter{{Name: aws.String("r"), Value: aws.String("amer")}}, StatementName: aws.String("load-1")}))
	b := finished(t, ds, *batch.Id)
	if len(b.SubStatements) != 3 || b.SubStatements[2].Status != types.StatementStatusStringFinished || !*b.SubStatements[2].HasResultSet ||
		*b.SubStatements[0].Id != *batch.Id+":1" || b.SubStatements[1].ResultRows != 1 {
		t.Fatalf("batch %+v", b)
	}
	if n := must(ds.GetStatementResult(ctx, &redshiftdata.GetStatementResultInput{Id: aws.String(*batch.Id + ":3")})).Records[0][0]; n.(*types.FieldMemberLongValue).Value != 3 {
		t.Fatalf("count %+v", n)
	}
	st := run(`SELECT id, region, amount, qty, price, paid, sold, note FROM sales WHERE region = :region`, "region", "emea")
	res := must(ds.GetStatementResult(ctx, &redshiftdata.GetStatementResultInput{Id: st.Id}))
	var got []string
	for _, f := range res.Records[0] {
		switch v := f.(type) {
		case *types.FieldMemberLongValue:
			got = append(got, "long:"+strconv.FormatInt(v.Value, 10))
		case *types.FieldMemberStringValue:
			got = append(got, "string:"+v.Value)
		case *types.FieldMemberDoubleValue:
			got = append(got, "double:"+strconv.FormatFloat(v.Value, 'f', -1, 64))
		case *types.FieldMemberBooleanValue:
			got = append(got, "bool:"+strconv.FormatBool(v.Value))
		case *types.FieldMemberIsNull:
			got = append(got, "null")
		}
	}
	var typeNames []string
	for _, c := range res.ColumnMetadata {
		typeNames = append(typeNames, *c.TypeName)
	}
	if want := []string{"long:1", "string:emea", "string:12.50", "long:3", "double:4.25", "bool:true", "string:2024-05-01 10:00:00", "null"}; !slices.Equal(got, want) ||
		res.TotalNumRows != 1 || !slices.Equal(typeNames, []string{"int4", "varchar", "numeric", "int8", "float8", "bool", "timestamp", "varchar"}) {
		t.Fatalf("records %v, types %v, total %d", got, typeNames, res.TotalNumRows)
	}
	csv := must(ds.ExecuteStatement(ctx, &redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"),
		Sql: aws.String("SELECT region, qty FROM sales ORDER BY id"), ResultFormat: types.ResultFormatStringCsv, WaitTimeSeconds: aws.Int32(30)}))
	if csv.Status != types.StatementStatusStringFinished {
		t.Fatalf("waited for %+v", csv)
	}
	_, err := ds.GetStatementResult(ctx, &redshiftdata.GetStatementResultInput{Id: csv.Id})
	fails(t, err, "ValidationException")
	if r := must(ds.GetStatementResultV2(ctx, &redshiftdata.GetStatementResultV2Input{Id: csv.Id})); r.Records[0].(*types.QueryRecordsMemberCSVRecords).Value !=
		"region,qty\nemea,3\namer,1\napac,2\n" || r.ResultFormat != types.ResultFormatStringCsv {
		t.Fatalf("csv %+v", r.Records)
	}
	failed := must(ds.BatchExecuteStatement(ctx, &redshiftdata.BatchExecuteStatementInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"),
		Sqls: []string{"INSERT INTO sales (region) VALUES ('lost')", "SELECT 1/0", "SELECT 1"}}))
	eventually(t, "the failing batch", func() bool {
		f := must(ds.DescribeStatement(ctx, &redshiftdata.DescribeStatementInput{Id: failed.Id}))
		if f.Status != types.StatusStringFailed {
			return false
		}
		if !strings.Contains(*f.Error, "division by zero") || f.SubStatements[1].Status != types.StatementStatusStringFailed ||
			f.SubStatements[2].Status != types.StatementStatusStringAborted {
			t.Fatalf("failed batch %+v", f)
		}
		return true
	})
	lost := must(ds.GetStatementResult(ctx, &redshiftdata.GetStatementResultInput{Id: run("SELECT count(*) FROM sales WHERE region = 'lost'").Id}))
	if lost.Records[0][0].(*types.FieldMemberLongValue).Value != 0 {
		t.Fatal("the failed batch was not rolled back")
	}
	slow := must(ds.ExecuteStatement(ctx, &redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"),
		Sql: aws.String("SELECT pg_sleep(30)")}))
	if c := must(ds.CancelStatement(ctx, &redshiftdata.CancelStatementInput{Id: slow.Id})); !*c.Status {
		t.Fatal("not cancelled")
	}
	if s := must(ds.DescribeStatement(ctx, &redshiftdata.DescribeStatementInput{Id: slow.Id})); s.Status != types.StatusStringAborted {
		t.Fatalf("cancelled %+v", s)
	}
	_, err = ds.CancelStatement(ctx, &redshiftdata.CancelStatementInput{Id: st.Id})
	fails(t, err, "ValidationException")
	if l := must(ds.ListStatements(ctx, &redshiftdata.ListStatementsInput{StatementName: aws.String("load")})).Statements; len(l) != 1 ||
		!*l[0].IsBatchStatement || len(l[0].QueryStrings) != 3 {
		t.Fatalf("listed %+v", l)
	}
	secret := must(sm.CreateSecret(ctx, &secretsmanager.CreateSecretInput{Name: aws.String("redshift-login"),
		SecretString: aws.String(`{"username":"awsuser","password":"Secret123"}`)}))
	as := must(ds.ExecuteStatement(ctx, &redshiftdata.ExecuteStatementInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"),
		SecretArn: secret.ARN, Sql: aws.String("SELECT current_user")}))
	finished(t, ds, *as.Id)
	if u := must(ds.GetStatementResult(ctx, &redshiftdata.GetStatementResultInput{Id: as.Id})).Records[0][0]; u.(*types.FieldMemberStringValue).Value != "awsuser" {
		t.Fatalf("secret login ran as %+v", u)
	}

	// 3. the catalog
	tables := must(ds.ListTables(ctx, &redshiftdata.ListTablesInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"),
		SchemaPattern: aws.String("public")})).Tables
	if len(tables) != 1 || *tables[0].Name != "sales" || *tables[0].Schema != "public" || *tables[0].Type != "TABLE" {
		t.Fatalf("tables %+v", tables)
	}
	cols := must(ds.DescribeTable(ctx, &redshiftdata.DescribeTableInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"),
		Schema: aws.String("public"), Table: aws.String("sales")}))
	if *cols.TableName != "sales" || len(cols.ColumnList) != 8 || *cols.ColumnList[2].Name != "amount" || cols.ColumnList[2].Precision != 10 ||
		cols.ColumnList[2].Scale != 2 || cols.ColumnList[0].Precision != 10 || *cols.ColumnList[0].TypeName != "int4" || cols.ColumnList[0].Nullable != 0 {
		t.Fatalf("columns %+v", cols.ColumnList)
	}
	if dbs := must(ds.ListDatabases(ctx, &redshiftdata.ListDatabasesInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics")})).Databases; !slices.Contains(dbs, "analytics") {
		t.Fatalf("databases %v", dbs)
	}
	if schemas := must(ds.ListSchemas(ctx, &redshiftdata.ListSchemasInput{ClusterIdentifier: aws.String(id), Database: aws.String("analytics"),
		SchemaPattern: aws.String("pub%")})).Schemas; !slices.Equal(schemas, []string{"public"}) {
		t.Fatalf("schemas %v", schemas)
	}

	// 4. temporary credentials log in, as the user they stand for
	cr := must(rs.GetClusterCredentials(ctx, &redshift.GetClusterCredentialsInput{ClusterIdentifier: aws.String(id), DbUser: aws.String("awsuser"),
		DbName: aws.String("analytics")}))
	var who string
	var rows int
	conn := login(t, port, *cr.DbUser, *cr.DbPassword, "analytics")
	if err := conn.QueryRow(ctx, "SELECT current_user, (SELECT count(*) FROM sales)").Scan(&who, &rows); err != nil || who != "awsuser" || rows != 3 {
		t.Fatalf("as %s: %s %d %v", *cr.DbUser, who, rows, err)
	}
	ci := must(rs.GetClusterCredentialsWithIAM(ctx, &redshift.GetClusterCredentialsWithIAMInput{ClusterIdentifier: aws.String(id)}))
	if err := login(t, port, *ci.DbUser, *ci.DbPassword, "analytics").QueryRow(ctx, "SELECT current_user").Scan(&who); err != nil || who != "IAM:root" {
		t.Fatalf("as %s: %s %v", *ci.DbUser, who, err)
	}

	// 5. a serverless workgroup answers the Data API
	must(sl.CreateNamespace(ctx, &redshiftserverless.CreateNamespaceInput{NamespaceName: aws.String(id), AdminUsername: aws.String("admin"),
		AdminUserPassword: aws.String("Secret123")}))
	must(sl.CreateWorkgroup(ctx, &redshiftserverless.CreateWorkgroupInput{WorkgroupName: aws.String(id), NamespaceName: aws.String(id)}))
	var wgPort int32
	eventually(t, "the workgroup", func() bool {
		w := must(sl.GetWorkgroup(ctx, &redshiftserverless.GetWorkgroupInput{WorkgroupName: aws.String(id)})).Workgroup
		if w.Status == "FAILED" {
			t.Fatalf("the container failed: %+v", w)
		}
		if w.Status == "AVAILABLE" {
			wgPort = *w.Endpoint.Port
		}
		return wgPort != 0
	})
	answer := must(ds.ExecuteStatement(ctx, &redshiftdata.ExecuteStatementInput{WorkgroupName: aws.String(id), Database: aws.String("dev"),
		Sql: aws.String("SELECT 41 + 1 AS answer")}))
	finished(t, ds, *answer.Id)
	if r := must(ds.GetStatementResult(ctx, &redshiftdata.GetStatementResultInput{Id: answer.Id})); r.Records[0][0].(*types.FieldMemberLongValue).Value != 42 ||
		*r.ColumnMetadata[0].Name != "answer" {
		t.Fatalf("answer %+v", r)
	}
	gc := must(sl.GetCredentials(ctx, &redshiftserverless.GetCredentialsInput{WorkgroupName: aws.String(id)}))
	if err := login(t, wgPort, *gc.DbUser, *gc.DbPassword, "dev").QueryRow(ctx, "SELECT current_user").Scan(&who); err != nil || who != "IAM:root" {
		t.Fatalf("as %s: %s %v", *gc.DbUser, who, err)
	}

	// 6. deleting removes the containers
	must(rs.DeleteCluster(ctx, &redshift.DeleteClusterInput{ClusterIdentifier: aws.String(id), SkipFinalClusterSnapshot: aws.Bool(true)}))
	must(sl.DeleteWorkgroup(ctx, &redshiftserverless.DeleteWorkgroupInput{WorkgroupName: aws.String(id)}))
	must(sl.DeleteNamespace(ctx, &redshiftserverless.DeleteNamespaceInput{NamespaceName: aws.String(id)}))
	eventually(t, "container removal", func() bool {
		a, err1 := d.List(ctx, docker.LabelResource+"="+id, docker.LabelService+"=redshift")
		b, err2 := d.List(ctx, docker.LabelResource+"="+id, docker.LabelService+"=redshift-serverless")
		return err1 == nil && err2 == nil && len(a)+len(b) == 0
	})
}
